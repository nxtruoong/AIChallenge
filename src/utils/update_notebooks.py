                "            if key not in item_map:\n",
                "                item_map[key] = item\n",
                "                rrf_scores[key] = 0.0\n",
                "            rrf_scores[key] += 1.0 / (k + rank + 1)\n",
                "\n",
                "    sorted_keys = sorted(rrf_scores.keys(), key=lambda x: rrf_scores[x], reverse=True)\n",
                "    fused = []\n",
                "    for k_val in sorted_keys:\n",
                "        item = item_map[k_val].copy()\n",
                "        item['score'] = rrf_scores[k_val]\n",
