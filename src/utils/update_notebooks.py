                "# Cell 5: Score Fusion Engine (RRF & Weighted Fallback)\n",
                "def reciprocal_rank_fusion(results_lists, k=60):\n",
                "    \"\"\"Scale-free RRF algorithm: score(doc) = sum(1 / (k + rank))\"\"\"\n",
                "    rrf_scores = {}\n",
                "    item_map = {}\n",
                "\n",
